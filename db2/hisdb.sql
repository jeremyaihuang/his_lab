-- 仁心醫院 HIS 資料庫（HISDB）schema 與示範資料
-- 由 db2/init-hisdb.sh 以 db2inst1 身分執行：db2 -tvf hisdb.sql
CONNECT TO HISDB;

-- ---------- 基本資料 ----------
CREATE TABLE HIS.DEPARTMENTS (
  DEPT_CODE  CHAR(4)      NOT NULL PRIMARY KEY,
  DEPT_NAME  VARCHAR(40)  NOT NULL
);

CREATE TABLE HIS.DOCTORS (
  DOCTOR_ID  INTEGER      NOT NULL PRIMARY KEY,
  NAME       VARCHAR(40)  NOT NULL,
  DEPT_CODE  CHAR(4)      NOT NULL
);

CREATE TABLE HIS.PATIENTS (
  PATIENT_ID INTEGER      NOT NULL PRIMARY KEY,
  CHART_NO   CHAR(10)     NOT NULL,
  NAME       VARCHAR(40)  NOT NULL,
  GENDER     CHAR(1)      NOT NULL,
  BIRTH_DATE DATE         NOT NULL,
  NHI_CARD   VARCHAR(12),
  PHONE      VARCHAR(20),
  CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE UNIQUE INDEX HIS.IX_PAT_CHART ON HIS.PATIENTS (CHART_NO);

-- ---------- 掛號 ----------
CREATE TABLE HIS.APPOINTMENTS (
  APPT_ID    BIGINT       NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  PATIENT_ID INTEGER      NOT NULL,
  DOCTOR_ID  INTEGER      NOT NULL,
  DEPT_CODE  CHAR(4)      NOT NULL,
  VISIT_DATE DATE         NOT NULL,
  SEQ_NO     INTEGER      NOT NULL,
  STATUS     VARCHAR(10)  NOT NULL DEFAULT 'BOOKED',
  CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE INDEX HIS.IX_APPT_DOC_DATE ON HIS.APPOINTMENTS (DOCTOR_ID, VISIT_DATE);
CREATE INDEX HIS.IX_APPT_PATIENT ON HIS.APPOINTMENTS (PATIENT_ID);

-- ---------- 病歷（大表；情境 slow-sql 會刪掉 IX_MR_PATIENT 造成全表掃描） ----------
CREATE TABLE HIS.MEDICAL_RECORDS (
  RECORD_ID  BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PATIENT_ID INTEGER      NOT NULL,
  DOCTOR_ID  INTEGER      NOT NULL,
  VISIT_DATE DATE         NOT NULL,
  ICD10      VARCHAR(8)   NOT NULL,
  DIAGNOSIS  VARCHAR(120) NOT NULL,
  NOTES      VARCHAR(400)
);
CREATE INDEX HIS.IX_MR_PATIENT ON HIS.MEDICAL_RECORDS (PATIENT_ID, VISIT_DATE);

-- ---------- 藥局 ----------
CREATE TABLE HIS.DRUGS (
  DRUG_ID    INTEGER      NOT NULL PRIMARY KEY,
  DRUG_CODE  VARCHAR(12)  NOT NULL,
  NAME       VARCHAR(60)  NOT NULL,
  STOCK      INTEGER      NOT NULL,
  UNIT_PRICE DECIMAL(9,2) NOT NULL
);

CREATE TABLE HIS.PRESCRIPTIONS (
  RX_ID      BIGINT       NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  PATIENT_ID INTEGER      NOT NULL,
  DOCTOR_ID  INTEGER      NOT NULL,
  APPT_ID    BIGINT,
  STATUS     VARCHAR(10)  NOT NULL DEFAULT 'NEW',
  TOTAL      DECIMAL(11,2),
  CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE INDEX HIS.IX_RX_PATIENT ON HIS.PRESCRIPTIONS (PATIENT_ID);

CREATE TABLE HIS.PRESCRIPTION_ITEMS (
  RX_ID      BIGINT       NOT NULL,
  DRUG_ID    INTEGER      NOT NULL,
  QTY        INTEGER      NOT NULL,
  DAYS       INTEGER      NOT NULL,
  PRIMARY KEY (RX_ID, DRUG_ID)
);

-- ---------- 檢驗 ----------
CREATE TABLE HIS.LAB_ORDERS (
  ORDER_ID   BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PATIENT_ID INTEGER      NOT NULL,
  TEST_CODE  VARCHAR(10)  NOT NULL,
  TEST_NAME  VARCHAR(40)  NOT NULL,
  STATUS     VARCHAR(10)  NOT NULL,
  RESULT     VARCHAR(60),
  CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP
);
CREATE INDEX HIS.IX_LAB_PATIENT ON HIS.LAB_ORDERS (PATIENT_ID);

